  await p.goto("/julianjoseph", { timeout: 120_000 });
  await p.screenshot({ path: DIR + "/phone-landing.png", fullPage: true });
  await p.goto("/julianjoseph/30min?back=1", { timeout: 120_000 });
  await p.getByRole("button", { name: "Tuesday, October 8 - Times available" }).waitFor({ timeout: 60_000 });
  await p.screenshot({ path: DIR + "/phone-calendar.png", fullPage: true });
  await p.getByRole("button", { name: "Tuesday, October 8 - Times available" }).click();
  await p.waitForTimeout(500);
  await p.getByRole("list", { name: "Select a time" }).getByRole("button").first().click();
  await p.waitForTimeout(400);
  await p.screenshot({ path: DIR + "/phone-times.png" });
  await p.getByRole("button", { name: "Next", exact: true }).click();
  await p.waitForTimeout(800);
  await p.screenshot({ path: DIR + "/phone-details.png", fullPage: true });
  await p.setViewportSize({ width: 768, height: 1024 });
  await p.goto("/julianjoseph/30min?date=2030-10-08", { timeout: 120_000 });
  await p.waitForTimeout(1500);
  await p.screenshot({ path: DIR + "/tablet.png", fullPage: true });
  await phone.close();
